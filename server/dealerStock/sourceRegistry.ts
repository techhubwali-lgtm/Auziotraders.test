const ALLOWLISTED_DOMAINS = new Set(
  CANDIDATE_DEALER_SOURCES.map((s) => s.domain.toLowerCase())
);

/**
 * Strict SSRF guard: only permits HTTPS public domains and rejects private,
 * loopback, link-local, metadata, or non-HTTP(S) targets.
 */
export function validateSafeExternalUrl(
  rawUrl: string,
  requireAllowlist = true
): { ok: true; url: URL } | { ok: false; reason: string } {
  let parsed: URL;
  try {
    parsed = new URL(rawUrl.trim());
  } catch {
    return { ok: false, reason: 'Invalid URL format.' };
  }

  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    return { ok: false, reason: 'Only HTTPS/HTTP URLs are permitted.' };
  }

  const host = parsed.hostname.toLowerCase();
  if (
    host === 'localhost' ||
    host === '::1' ||
    host.endsWith('.local') ||
    host.endsWith('.internal') ||
    /^127\./.test(host) ||
    /^10\./.test(host) ||
    /^192\.168\./.test(host) ||
    /^169\.254\./.test(host) ||
    /^172\.(1[6-9]|2\d|3[0-1])\./.test(host) ||
    /^0\./.test(host) ||
    /^\[?fe80:/i.test(host) ||
    /^\[?fc00:/i.test(host) ||
    /^\[?fd/i.test(host)
  ) {
    return { ok: false, reason: 'Private, loopback, or metadata network addresses are blocked.' };
  }

  if (requireAllowlist) {
    const normalizedHost = host.replace(/^www\./, '');
    const allowed = Array.from(ALLOWLISTED_DOMAINS).some(
      (d) => d === host || d.replace(/^www\./, '') === normalizedHost
    );
    if (!allowed) {
      return {
        ok: false,
        reason: `Host "${host}" is not in the registered Japanese dealer allowlist.`,
      };
    }
  }

  return { ok: true, url: parsed };
}

export function getCandidateSourceById(id: string): DealerSource | undefined {
  return CANDIDATE_DEALER_SOURCES.find((s) => s.id === id);
}
