export const WORLD_COUNTRIES: WorldCountryOption[] = RAW_WORLD_COUNTRIES.map((country) => {
  const ports: WorldPortOption[] = country.ports.map(([unLocode, name, verifiedPortId, corridorNote]) => ({
    id: verifiedPortId || `${country.code.toLowerCase()}-${unLocode.toLowerCase()}`,
    unLocode,
    name,
    countryCode: country.code,
    countryName: country.name,
    region: country.region,
    rateAvailable: Boolean(verifiedPortId),
    verifiedPortId,
    corridorNote,
  }));

  return {
    code: country.code,
    name: country.name,
    region: country.region,
    supportedShipping: ports.some((p) => p.rateAvailable),
    ports,
  };
});

export const ALL_WORLD_PORTS: WorldPortOption[] = WORLD_COUNTRIES.flatMap((c) => c.ports);

const PORT_BY_ID_MAP = new Map<string, WorldPortOption>(ALL_WORLD_PORTS.map((p) => [p.id, p]));
const COUNTRY_BY_CODE_MAP = new Map<string, WorldCountryOption>(WORLD_COUNTRIES.map((c) => [c.code, c]));

export function getWorldPortOptionById(portId: string): WorldPortOption {
  return PORT_BY_ID_MAP.get(portId) || ALL_WORLD_PORTS[0];
}

export function getWorldCountryByCode(countryCode: string): WorldCountryOption {
  return COUNTRY_BY_CODE_MAP.get(countryCode.toUpperCase()) || WORLD_COUNTRIES[0];
}

export function getWorldCountryByPortId(portId: string): WorldCountryOption {
  const port = getWorldPortOptionById(portId);
  return getWorldCountryByCode(port.countryCode);
}
